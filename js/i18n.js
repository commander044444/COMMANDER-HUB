function t(key) {
  const lang = (window.AppState && AppState.language) || 'fa';
  return (I18N[lang] && I18N[lang][key]) || (I18N.fa[key]) || key;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    el.title = t(key);
  });
}

function setLanguage(lang) {
  if (!I18N[lang]) return;
  AppState.language = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr';
  document.getElementById('lang-label').textContent = lang === 'fa' ? 'EN' : 'FA';
  applyTranslations();
  Storage.save('language', lang);
  if (window.renderCurrentView) renderCurrentView();
}
